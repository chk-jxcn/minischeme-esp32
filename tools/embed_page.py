#!/usr/bin/env python3
"""Embeds the settings web page in the firmware, gzip-compressed.

    python tools/embed_page.py SRC OUT

main/setup_page.html -> setup_page_html.h (setup_page_gz[], SETUP_PAGE_GZ_LEN),
served at / with Content-Encoding: gzip. main/CMakeLists.txt runs it at every
build where the page changed (the header is generated into the build folder,
never committed, so it cannot fall behind the page).
"""
import gzip
import os
import sys


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, out = sys.argv[1], sys.argv[2]
    html = open(src, 'rb').read().replace(b'\r\n', b'\n')
    data = gzip.compress(html, compresslevel=9, mtime=0)  # mtime 0: the same page gives the same bytes
    lines = ['/**', ' * @file setup_page_html.h',
             ' * @brief The settings web page (setup_page.html), gzip-compressed.',
             ' *        Generated by tools/embed_page.py at build time; do not edit.', ' */',
             '#ifndef SETUP_PAGE_HTML_H', '#define SETUP_PAGE_HTML_H', '',
             '#include <stdint.h>', '',
             f'#define SETUP_PAGE_GZ_LEN {len(data)}', '',
             'static const uint8_t setup_page_gz[] = {']
    for i in range(0, len(data), 16):
        lines.append('    ' + ', '.join(f'0x{b:02X}' for b in data[i:i + 16]) + ',')
    lines += ['};', '', '#endif /* SETUP_PAGE_HTML_H */', '']
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print(f'{os.path.basename(src)}: {len(html)} bytes -> {len(data)} bytes gzip -> {out}')


if __name__ == '__main__':
    main()
