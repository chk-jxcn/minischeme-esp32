"""Writes components/minischeme/src/minischeme_hanzi_table.h: the character tables of the
simplified / traditional Chinese conversion (minischeme_hanzi.c).

The pairs come from the Windows conversion (LCMapStringEx with LCMAP_SIMPLIFIED_CHINESE /
LCMAP_TRADITIONAL_CHINESE), character by character over U+4E00..U+9FFF, so this tool runs on
Windows only; the generated header is committed. A character with several counterparts keeps
the one Windows picks (it leaves ambiguous ones such as 后 / 里 / 面 unchanged); OVERRIDES adds
a few it leaves alone.

    python tools/make_hanzi_table.py
"""
import ctypes
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'components', 'minischeme', 'src', 'minischeme_hanzi_table.h')

LCMAP_SIMPLIFIED_CHINESE = 0x02000000
LCMAP_TRADITIONAL_CHINESE = 0x04000000

# (direction, from, to) the Windows tables leave unchanged
OVERRIDES = [
    ('t2s', '後', '后'),
]


def convert(text, flag):
    from ctypes import wintypes
    fn = ctypes.WinDLL('kernel32', use_last_error=True).LCMapStringEx
    fn.argtypes = [wintypes.LPCWSTR, wintypes.DWORD, wintypes.LPCWSTR, ctypes.c_int, wintypes.LPWSTR,
                   ctypes.c_int, ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p]
    buf = ctypes.create_unicode_buffer(len(text) + 16)
    n = fn('zh-CN', flag, text, len(text), buf, len(buf), None, None, None)
    if n != len(text):
        sys.exit(f'LCMapStringEx returned {n} characters for {len(text)}')
    return buf.value[:n]


def pairs(flag, direction):
    chars = ''.join(chr(c) for c in range(0x4E00, 0xA000))
    out = {a: b for a, b in zip(chars, convert(chars, flag)) if a != b and ord(b) <= 0xFFFF}
    for d, a, b in OVERRIDES:
        if d == direction:
            out[a] = b
    return sorted(out.items())


def c_array(name, values):
    lines = [f'static const uint16_t {name}[{len(values)}] = {{']
    for i in range(0, len(values), 12):
        lines.append('    ' + ', '.join(f'0x{v:04X}' for v in values[i:i + 12]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    if os.name != 'nt':
        sys.exit('make_hanzi_table.py uses the Windows conversion: run it on Windows')
    s2t = pairs(LCMAP_TRADITIONAL_CHINESE, 's2t')
    t2s = pairs(LCMAP_SIMPLIFIED_CHINESE, 't2s')
    parts = [
        '/* Generated by tools/make_hanzi_table.py (the Windows simplified / traditional Chinese',
        ' * conversion, character by character): do not edit. Sorted by the first array. */',
        '#ifndef MINISCHEME_HANZI_TABLE_H',
        '#define MINISCHEME_HANZI_TABLE_H',
        '',
        '#include <stdint.h>',
        '',
        f'#define HANZI_S2T_COUNT {len(s2t)}',
        f'#define HANZI_T2S_COUNT {len(t2s)}',
        '',
        '/* simplified -> traditional */',
        c_array('HANZI_S2T_FROM', [ord(a) for a, _ in s2t]),
        c_array('HANZI_S2T_TO', [ord(b) for _, b in s2t]),
        '',
        '/* traditional -> simplified */',
        c_array('HANZI_T2S_FROM', [ord(a) for a, _ in t2s]),
        c_array('HANZI_T2S_TO', [ord(b) for _, b in t2s]),
        '',
        '#endif',
        '',
    ]
    with open(OUT, 'w', encoding='ascii', newline='\n') as f:
        f.write('\n'.join(parts))
    print(f'{os.path.relpath(OUT, ROOT)}: {len(s2t)} simplified -> traditional, {len(t2s)} traditional -> simplified')


if __name__ == '__main__':
    main()
